import math
from penguin import Penguin

def read_penguin_row(row_number):
    penguin_row = ""

    # open the CSV file and skip the header row
    with open("PalmerPenguins.csv", "r") as penguin_file:
        penguin_file.readline()

        current_row = 1

        # search for the requested data row
        for row in penguin_file:
            if current_row == row_number:
                penguin_row = row.strip()
                break

            current_row += 1

    # return the requested row as a string
    return penguin_row

SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"

NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151


def calculate_percentage(count, total):
    return count / total * 100


def classify_species(percent):
    if percent < 25:
        return "small"
    elif percent >= 25 and percent < 40:
        return "medium"
    else:
        return "large"


def get_position_description(selected_species,
                             largest_species,
                             smallest_species):
    if selected_species == largest_species:
        return "largest"
    elif selected_species == smallest_species:
        return "smallest"
    else:
        return "middle-sized"


def display_species_statistics(names, counts, percentages):
    for index, name in enumerate(names):
        print(f"{name}:{counts[index]}"
              f"({percentages[index]:.2f}%)")


def display_penguin_observation(sample_number, species,
                                bill_length, bill_depth,
                                body_mass, sex):
    print("Sample Penguin Observation")
    print(f"{'Sample Number:':<14}{sample_number}")
    print(f"{'Species:':<14}{species}")
    print(f"{'Bill length:':<14}{bill_length} mm")
    print(f"{'Bill depth:':<14}{bill_depth} mm")
    print(f"{'Body mass:':<14}{body_mass} g")
    print(f"{'Sex:':<14}{sex}")
    print()


